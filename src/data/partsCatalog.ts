// Utility functions for querying the catalog
export const getPartBySku = (sku: string): AutoPart | undefined => {
  return PARTS_CATALOG_DATA.find((p) => p.sku.toLowerCase() === sku.toLowerCase());
};

export const getPartsByFamily = (familyId: string): AutoPart[] => {
  return PARTS_CATALOG_DATA.filter((p) => p.familyId === familyId);
};

export const getPartsBySubfamily = (subfamilyId: string): AutoPart[] => {
  return PARTS_CATALOG_DATA.filter((p) => p.subfamilyId === subfamilyId);
};

export const getCompatibleParts = (brand: string, model?: string): AutoPart[] => {
  const brandLower = brand.toLowerCase();
  const modelLower = (model || '').toLowerCase();
  return PARTS_CATALOG_DATA.filter((p) => {
    const comp = (p.compatibleVehicle || '').toLowerCase();
    const hasVehicleMatch = p.vehicleCompatibility?.some(
      (v) => v.brand.toLowerCase().includes(brandLower) && (!modelLower || v.model.toLowerCase().includes(modelLower))
    );
    return comp.includes(brandLower) || (modelLower && comp.includes(modelLower)) || comp.includes('universal') || hasVehicleMatch;
  });
};
